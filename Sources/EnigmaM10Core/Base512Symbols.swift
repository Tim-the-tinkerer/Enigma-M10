    public static let alphabet: String = {
        var scalars = String.UnicodeScalarView()
        for point in codePoints {
            guard let scalar = Unicode.Scalar(point) else { continue }
            scalars.append(scalar)
        }
        return String(scalars)
    }()

    public static let utf8BytesPerSymbol = 2

    public static func symbolCount(for byteCount: Int) -> Int {
        guard byteCount > 0 else { return 0 }
        return (byteCount * 8 + 8) / 9
    }

    public static func indexToChar(_ index: Int) -> Character {
        let point = codePoints[index]
        return Character(Unicode.Scalar(point)!)
    }

    public static func charToIndex(_ character: Character) -> Int? {
        guard character.unicodeScalars.count == 1,
              let scalar = character.unicodeScalars.first else {
            return nil
        }
        return scalarToIndex[scalar.value]
    }

    public static func isValidSymbol(_ character: Character) -> Bool {
        charToIndex(character) != nil
    }

    public static func filteredSymbols(_ text: String) -> String {
        String(text.filter { isValidSymbol($0) })
    }

    public static func encode(_ data: Data) -> String {
        guard !data.isEmpty else { return "" }
        var acc: UInt64 = 0
        var nbits = 0
        var symbols = ""
        symbols.reserveCapacity(symbolCount(for: data.count))
        for byte in data {
            acc = (acc << 8) | UInt64(byte)
            nbits += 8
            while nbits >= 9 {
                nbits -= 9
                let digit = Int((acc >> nbits) & 0x1FF)
                acc &= nbits == 0 ? 0 : (UInt64(1) << nbits) - 1
                symbols.append(indexToChar(digit))
            }
        }
        if nbits > 0 {
            let digit = Int((acc << (9 - nbits)) & 0x1FF)
            symbols.append(indexToChar(digit))
        }
        return symbols
    }

    public static func decode(_ symbols: String, storedLength: Int) -> Data? {
        guard storedLength >= 0 else { return nil }
        if storedLength == 0 { return symbols.isEmpty ? Data() : nil }
        let expected = symbolCount(for: storedLength)
        let filtered = filteredSymbols(symbols)
        guard filtered.count == expected else { return nil }
        var acc: UInt64 = 0
        var nbits = 0
        var output = Data()
        output.reserveCapacity(storedLength)
        for character in filtered {
            guard let digit = charToIndex(character) else { return nil }
            acc = (acc << 9) | UInt64(digit)
            nbits += 9
            while nbits >= 8 && output.count < storedLength {
                nbits -= 8
                output.append(UInt8((acc >> nbits) & 0xFF))
                acc &= nbits == 0 ? 0 : (UInt64(1) << nbits) - 1
            }
        }
        guard output.count == storedLength else { return nil }
        if nbits > 0 {
            let mask = nbits == 0 ? 0 : (UInt64(1) << nbits) - 1
            if acc & mask != 0 { return nil }
        }
        return output
    }

    public static func utf8(ofSymbols symbols: String) -> Data {
        Data(symbols.utf8)
    }

    private static let scalarToIndex: [UInt32: Int] = {
        var map: [UInt32: Int] = [:]
        map.reserveCapacity(codePoints.count)
        for (index, point) in codePoints.enumerated() {
            map[point] = index
        }
        return map
    }()
